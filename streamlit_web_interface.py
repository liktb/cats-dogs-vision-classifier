import streamlit as st
from PIL import Image
import numpy as np
import tensorflow as tf  # or torch, depending on your model

# Page Configuration
st.set_page_config(
    page_title="Cat vs Dog Vision Classifier",
    page_icon="🐾",
    layout="centered"
)

# App Header
st.title("🐾 Cats vs. Dogs Vision Classifier")
st.write("Upload an image of a cat or a dog to see if the model can correctly identify it!")

# Model Caching & Loading
@st.cache_resource
def load_model():
    # Replace with your actual saved model path (e.g., .h5 or .pt)
    model = tf.keras.models.load_model("model/cats_dogs_model.h5")
    return model

with st.spinner("Loading model... Please wait."):
    model = load_model()

# File Uploader Widget
uploaded_file = st.file_uploader("Choose an image...", type=["jpg", "jpeg", "png"])

if uploaded_file is not None:
    # Open and display the uploaded image
    image = Image.open(uploaded_file)
    st.image(image, caption="Uploaded Image", use_column_width=True)

    st.write("")
    if st.button("Classify Image"):
        with st.spinner("Analyzing image..."):
            # Preprocess image to match training requirements (e.g., 224x224)
            image = image.resize((224, 224))
            img_array = np.array(image) / 255.0  # Normalize if needed

            # Handle grayscale or 4-channel RGBA images if necessary
            if img_array.shape[-1] == 4:
                img_array = img_array[..., :3]

            img_array = np.expand_dims(img_array, axis=0)

            # Make Prediction
            prediction = model.predict(img_array)[0][0]

            # Output Results (Assuming binary classification: 0 = Cat, 1 = Dog)
            if prediction > 0.5:
                confidence = prediction * 100
                st.success(f"**Prediction:** Dog 🐶 (Confidence: {confidence:.2f}%)")
            else:
                confidence = (1 - prediction) * 100
                st.success(f"**Prediction:** Cat 🐱 (Confidence: {confidence:.2f}%)")